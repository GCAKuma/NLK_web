from decimal import Decimal

from django.db import IntegrityError, transaction
from django.test import TestCase

from django.urls import reverse

from .models import (
    Attribute,
    AttributeValue,
    CalculatorRecommendation,
    Category,
    Product,
    ProductSpecification,
    ProductVariant,
    VariantAttributeValue,
)


class CategoryTests(TestCase):
    def test_slug_autogenerated(self):
        cat = Category.objects.create(name="Scientific Calculators")
        self.assertEqual(cat.slug, "scientific-calculators")


class ProductVariantConstraintTests(TestCase):
    def setUp(self):
        self.category = Category.objects.create(name="Calculators", slug="calculators")
        self.product = Product.objects.create(
            category=self.category, name="FX-991ES Plus", slug="fx-991es-plus"
        )

    def test_negative_price_rejected(self):
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                ProductVariant.objects.create(
                    product=self.product, sku="NEG-1", price=Decimal("-1.00")
                )

    def test_unique_sku(self):
        ProductVariant.objects.create(
            product=self.product, sku="SKU-1", price=Decimal("1000.00")
        )
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                ProductVariant.objects.create(
                    product=self.product, sku="SKU-1", price=Decimal("999.00")
                )

    def test_variant_label(self):
        variant = ProductVariant.objects.create(
            product=self.product, sku="COL-1", price=Decimal("1000.00")
        )
        color = Attribute.objects.create(name="Color")
        black = AttributeValue.objects.create(attribute=color, value="Black")
        VariantAttributeValue.objects.create(variant=variant, attribute_value=black)
        self.assertEqual(variant.label, "Black")


class AttributeValueConstraintTests(TestCase):
    def test_unique_attribute_value(self):
        color = Attribute.objects.create(name="Color")
        AttributeValue.objects.create(attribute=color, value="Red")
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                AttributeValue.objects.create(attribute=color, value="Red")


class ToolsTests(TestCase):
    def setUp(self):
        cat = Category.objects.create(name="Calculators", slug="calculators")
        self.p1 = Product.objects.create(category=cat, name="Model A", slug="model-a")
        self.p2 = Product.objects.create(category=cat, name="Model B", slug="model-b")
        ProductSpecification.objects.create(
            product=self.p1, spec_name="Functions", spec_value="417"
        )
        ProductSpecification.objects.create(
            product=self.p2, spec_name="Functions", spec_value="540"
        )

    def test_compare_comma_ids(self):
        resp = self.client.get(
            reverse("products:compare"), {"ids": f"{self.p1.id},{self.p2.id}"}
        )
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, "Functions")
        self.assertContains(resp, "417")
        self.assertContains(resp, "540")

    def test_compare_repeated_ids(self):
        resp = self.client.get(
            reverse("products:compare") + f"?ids={self.p1.id}&ids={self.p2.id}"
        )
        self.assertContains(resp, "417")
        self.assertContains(resp, "540")

    def test_calculator_finder_recommendation(self):
        CalculatorRecommendation.objects.create(
            student_type="al", recommended_product=self.p1, is_active=True
        )
        resp = self.client.get(reverse("products:calculator_finder"), {"type": "al"})
        self.assertEqual(resp.status_code, 200)
        self.assertContains(resp, "Model A")
